fn hsl(h: f32, s: f32, l: f32) -> [u8; 3] {
    let c = (1.0 - (2.0 * l - 1.0).abs()) * s;
    let hp = h / 60.0;
    let x = c * (1.0 - (hp % 2.0 - 1.0).abs());
    let (r, g, b) = match hp as i32 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    let m = l - c / 2.0;
    [((r + m) * 255.0).round() as u8, ((g + m) * 255.0).round() as u8, ((b + m) * 255.0).round() as u8]
}

pub fn nat_color(o: usize, iso: &str, eng: &str) -> [u8; 3] {
    let iso = if iso.is_empty() && eng == "Somaliland" { "xsl" } else { iso };
    if let Some(c) = col(iso) {
        return c;
    }
    let h = ((o as f64 * 137.508) % 360.0).floor() as f32;
    let l = (42 + (o * 7) % 14) as f32 / 100.0;
    hsl(h, 0.62, l)
}
